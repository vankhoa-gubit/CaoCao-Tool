export const translations = Object.fromEntries(['vi', 'en'].map((language, index) => [language, Object.fromEntries(Object.entries(strings).map(([key, values]) => [key, values[index]]))]));
export const storageKey = 'caocao.language';
export const normalizeLanguage = language => language === 'en' ? 'en' : 'vi';
export const localeFor = language => normalizeLanguage(language) === 'en' ? 'en-US' : 'vi-VN';

export function readLanguage() {
  try { return normalizeLanguage(localStorage.getItem(storageKey)); } catch { return 'vi'; }
}
export function saveLanguage(language) {
  try { localStorage.setItem(storageKey, normalizeLanguage(language)); } catch { /* The switch still works when storage is unavailable. */ }
}
function interpolate(template, values) {
  return template.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}
export function translate(language, key, values = {}) {
  return interpolate(translations[normalizeLanguage(language)][key] ?? translations.vi[key] ?? key, values);
}

